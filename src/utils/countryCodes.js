/**
 * Returns HTML string of <option> tags grouped by African Countries and Global/Other Countries.
 * @param {string} selectedCode - Currently selected dial code (e.g. '+233')
 */
export function getCountryOptionsHTML(selectedCode = '+233') {
  let html = `<optgroup label="🌍 African Countries">\n`;

  AFRICAN_COUNTRY_CODES.forEach(c => {
    const isSelected = c.code === selectedCode;
    html += `  <option value="${c.code}" ${isSelected ? 'selected' : ''}>${c.flag} ${c.name} (${c.code})</option>\n`;
  });

  html += `</optgroup>\n<optgroup label="🌐 Global & Other Countries">\n`;

  OTHER_COUNTRY_CODES.forEach(c => {
    const isSelected = c.code === selectedCode;
    html += `  <option value="${c.code}" ${isSelected ? 'selected' : ''}>${c.flag} ${c.name} (${c.code})</option>\n`;
  });

  html += `</optgroup>`;

  return html;
}
